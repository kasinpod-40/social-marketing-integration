function field(fieldName, type, options = {}) {
  return {
    fieldName,
    type,
    primary: options.primary === true,
    order: requirePositiveInteger(options.order, `${fieldName}.order`),
    required: options.required === true,
    nullable: options.nullable === true,
    keyRole: requireText(options.keyRole, `${fieldName}.keyRole`),
    sourcePath: requireText(options.sourcePath, `${fieldName}.sourcePath`),
    semantics: requireText(options.semantics, `${fieldName}.semantics`),
    importNote: requireText(options.importNote, `${fieldName}.importNote`),
    options: Object.freeze([...(options.options ?? [])]),
  };
}

function requirePositiveInteger(value, fieldName) {
  if (!Number.isSafeInteger(value) || value <= 0) throw new TypeError(`${fieldName} must be a positive integer`);
  return value;
}

function requireText(value, fieldName) {
  if (typeof value !== 'string' || value.trim() === '') throw new TypeError(`${fieldName} is required`);
  return value.trim();
}

function deepFreeze(value) {
  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;
  for (const child of Object.values(value)) deepFreeze(child);
  return Object.freeze(value);
}
